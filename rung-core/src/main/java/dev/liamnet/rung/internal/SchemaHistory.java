package dev.liamnet.rung.internal;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.HashMap;
import java.util.Map;
import java.util.regex.Pattern;

public final class SchemaHistory {

    private static final Pattern TABLE_PREFIX = Pattern.compile("[a-z_][a-z0-9_]*");
    private static final Pattern MODULE_NAME = Pattern.compile("[a-z0-9_]+");

    private final String table;

    public SchemaHistory(final String tablePrefix, final String module) {
        if (!isValidTablePrefix(tablePrefix)) {
            throw new IllegalArgumentException("Invalid table prefix: " + tablePrefix);
        }

        if (!isValidModuleName(module)) {
            throw new IllegalArgumentException("Invalid module name: " + module);
        }

        this.table = tablePrefix + module;
    }

    public static boolean isValidTablePrefix(final String tablePrefix) {
        return TABLE_PREFIX.matcher(tablePrefix).matches();
    }

    public static boolean isValidModuleName(final String module) {
        return MODULE_NAME.matcher(module).matches();
    }

    public String tableName() {
        return table;
    }

    public void ensureTable(final Connection connection) throws SQLException {
        final String ddl = "CREATE TABLE IF NOT EXISTS " + table + " ("
                + "installed_rank INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "version VARCHAR(50) NOT NULL UNIQUE,"
                + "script VARCHAR(255) NOT NULL,"
                + "checksum VARCHAR(64) NOT NULL,"
                + "installed_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)";
        try (Statement statement = connection.createStatement()) {
            statement.execute(ddl);
        }
    }

    public Map<String, String> appliedChecksums(final Connection connection) throws SQLException {
        final Map<String, String> applied = new HashMap<>();
        try (Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery("SELECT version, checksum FROM " + table)) {
            while (resultSet.next()) {
                applied.put(resultSet.getString("version"), resultSet.getString("checksum"));
            }
        }
        return applied;
    }

    public void record(final Connection connection, final MigrationFile migration) throws SQLException {
        try (PreparedStatement insert =
                connection.prepareStatement("INSERT INTO " + table + " (version, script, checksum) VALUES (?, ?, ?)")) {
            insert.setString(1, migration.version());
            insert.setString(2, migration.script());
            insert.setString(3, migration.checksum());
            insert.executeUpdate();
        }
    }

    public AppliedMigration latest(final Connection connection) throws SQLException {
        final String query = "SELECT version, script FROM " + table + " ORDER BY installed_rank DESC LIMIT 1";
        try (Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(query)) {
            if (!resultSet.next()) {
                return null;
            }

            return new AppliedMigration(resultSet.getString("version"), resultSet.getString("script"));
        }
    }

    public void delete(final Connection connection, final String version) throws SQLException {
        try (PreparedStatement delete = connection.prepareStatement("DELETE FROM " + table + " WHERE version = ?")) {
            delete.setString(1, version);
            delete.executeUpdate();
        }
    }
}
